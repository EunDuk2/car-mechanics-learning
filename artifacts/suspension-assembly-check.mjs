import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

export async function checkSuspensionAssembly(page) {
  const base = 'http://127.0.0.1:5173';
  const engineKey = 'auto-atlas.engine-assembly.v1';
  const suspensionKey = 'auto-atlas.suspension-assembly.v1';
  const state = () => page.evaluate(() => window.__assembly.getState());
  const open = async path => {
    await page.goto(base + path);
    await page.waitForFunction(() => window.__assembly);
  };
  const place = async (id, slot = id) => {
    await page.locator(`[data-part="${id}"]`).click();
    await page.locator('#target-slot').selectOption(slot);
    await page.locator('#place-slot').click();
  };
  // Keep a real existing engine attempt, including its note, while using the new lab.
  await open('/assembly.html');
  await place('block');
  await page.locator('#check').click();
  await page.locator('#attempt-note').fill('엔진 기록 보존 확인');
  const engineBefore = await page.evaluate(key => localStorage.getItem(key), engineKey);
  await page.locator('#history-close').click();
  await page.locator('[data-lab="suspension"]').click();
  await page.waitForFunction(() => window.__assembly?.system === 'suspension');
  assert.equal(await page.locator('h1').textContent(), '전륜·제동 조립 실습');
  const catalog = await page.evaluate(() => window.__assembly.catalog);
  assert.equal(catalog.length, 29);
  assert.equal(await page.locator('[data-part]').count(), 29);
  assert.equal(await page.locator('#progress-bar').getAttribute('max'), '29');
  assert.deepEqual((await state()).placements, {});
  assert.deepEqual((await state()).visibleReferences, []);
  assert.equal((await state()).selected, 'knuckle');
  await page.locator('[data-part="disc"]').click();
  assert.equal(await page.locator('.part-actions a').getAttribute('href'), '/mechanics.html?system=suspension&part=disc');
  assert(!(await page.locator('#target-slot').textContent()).includes('디스크'));
  await page.locator('#part-hint').click();
  assert.deepEqual((await state()).visibleReferences, ['disc']);
  assert.equal(await page.locator('#target-slot').inputValue(), '');
  await page.locator('#hints').check();
  assert.equal((await state()).visibleReferences.length, 29);
  await page.locator('#hints').uncheck();
  // Native inventory drag and pointer movement of a placed part.
  const target = await page.evaluate(() => window.__assembly.slotScreen('knuckle'));
  await page.locator('[data-part="knuckle"]').hover();
  await page.mouse.down();
  await page.mouse.move(target.x, target.y, {steps: 15});
  await page.mouse.up();
  assert.equal((await state()).placements.knuckle?.slot, 'knuckle');
  const canvas = await page.locator('#canvas').boundingBox();
  await page.mouse.move(target.x, target.y);
  await page.mouse.down();
  await page.mouse.move(canvas.x + 30, canvas.y + canvas.height - 60, {steps: 15});
  await page.mouse.up();
  assert.equal((await state()).placements.knuckle.slot, null);
  await page.locator('#undo').click();
  await place('pad--1', 'pad-1');
  await place('pad-1');
  await page.locator('[data-rotate="0"]').click();
  const bad = await page.evaluate(() => window.__assembly.inspect());
  assert.equal(bad.missing, 26);
  assert(bad.results.find(r => r.id === 'pad--1').issues.includes('wrong-slot'));
  assert(bad.results.find(r => r.id === 'pad-1').issues.includes('occupied'));
  assert(bad.results.find(r => r.id === 'pad-1').issues.includes('rotation'));
  await page.locator('#check').click();
  await page.locator('#attempt-note').fill('패드의 안쪽과 바깥쪽을 구분하기');
  await page.locator('#history-close').click();
  await page.reload();
  await page.waitForFunction(() => window.__assembly);
  assert.equal((await state()).attempts[0].note, '패드의 안쪽과 바깥쪽을 구분하기');
  assert.deepEqual((await state()).hintUsage, {allViews: 1, parts: ['disc']});
  assert.deepEqual((await state()).visibleReferences, []);
  await page.locator('#restart').click();
  await page.locator('#restart-yes').click();
  assert.equal((await state()).attempts.length, 1);
  assert.deepEqual((await state()).hintUsage, {allViews: 0, parts: []});
  await page.locator('#history-open').click();
  await page.locator('#resume-attempt').click();
  await page.locator('#resume-yes').click();
  assert.equal((await state()).placements['pad--1'].slot, 'pad-1');
  await page.locator('#restart').click();
  await page.locator('#restart-yes').click();
  for (const part of catalog) await place(part.id);
  assert.equal(await page.evaluate(() => window.__assembly.inspect().passed), true);
  await page.locator('#spread').fill('0');
  assert(await page.evaluate(() => window.__assembly.parts.every(p => p.position.distanceTo(p.userData.base) < 1e-8)));
  await page.locator('#shell').uncheck();
  await page.locator('#view-home').click();
  await page.screenshot({path: 'artifacts/suspension-assembly-complete.png'});
  await page.locator('#check').click();
  assert((await page.locator('#report h2').textContent()).includes('29개'));
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-history').click();
  const download = await downloadPromise;
  assert(download.suggestedFilename().startsWith('suspension-assembly-history-'));
  const exported = JSON.parse(await fs.readFile(await download.path(), 'utf8'));
  assert.equal(exported.catalog.length, 29);
  assert.equal(exported.attempts.at(-1).assessment.score, 100);
  await page.locator('#history-close').click();
  const suspensionBefore = await page.evaluate(key => localStorage.getItem(key), suspensionKey);
  assert.equal(await page.evaluate(key => localStorage.getItem(key), engineKey), engineBefore);
  await page.locator('[data-lab="engine"]').click();
  await page.waitForFunction(() => window.__assembly?.system === 'engine');
  assert.equal((await state()).placements.block.slot, 'block');
  assert.equal((await state()).attempts[0].note, '엔진 기록 보존 확인');
  await page.locator('[data-lab="suspension"]').click();
  await page.waitForFunction(() => window.__assembly?.system === 'suspension');
  assert.equal(await page.evaluate(key => localStorage.getItem(key), suspensionKey), suspensionBefore);
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: 'artifacts/suspension-assembly-mobile.png', fullPage: true});
  assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth));
  await page.locator('#history-open').click();
  assert(!await page.locator('#history').evaluate(el => el.scrollWidth > el.clientWidth));
  await page.locator('#history-close').click();
  await page.locator('#learning-link').click();
  await page.waitForFunction(() => window.__mechanics?.system === 'suspension');
  assert.equal(await page.locator('.assembly-entry').getAttribute('href'), '/assembly.html?system=suspension');
  await page.locator('[data-system="engine"]').click();
  assert.equal(await page.locator('.assembly-entry').getAttribute('href'), '/assembly.html');
}
